CITY_PREPOSITIONS: frozenset[str] = frozenset({"в", "у", "во", "in", "для", "по"})


class CityNormalizer:
    def normalize(self, phrase: str) -> str:
        cleaned = phrase.strip().lower()
        if not cleaned:
            return ""
        if cleaned in KNOWN_LOCATIVES:
            return KNOWN_LOCATIVES[cleaned]
        words = cleaned.split()
        restored = [self._restore(word) for word in words]
        return " ".join(word.capitalize() for word in restored)

    @staticmethod
    def _restore(word: str) -> str:
        if word in KNOWN_LOCATIVES:
            return KNOWN_LOCATIVES[word].lower()
        for suffix, replacement in _SUFFIX_RULES:
            if word.endswith(suffix) and len(word) - len(suffix) >= 2:
                return word[: -len(suffix)] + replacement
        return word
